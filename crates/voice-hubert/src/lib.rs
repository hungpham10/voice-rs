//! voice-hubert — HuBERT/ContentVec embedder via burn-onnx codegen.
//!
//! The ONNX model is expected at `sources/onnx_hubert/model.onnx` with
//! accompanying `config.json` and `preprocessor_config.json`.
//!
//! Usage:
//! ```no_run
//! use voice_hubert::{HubertEmbedder, PreprocessorConfig, NormalizeMode};
//! use hound::WavReader;
//!
//! let mut embedder = HubertEmbedder::new()?;
//! let mut reader = WavReader::open("audio.wav")?;
//! let samples: Vec<f32> = reader.samples::<i16>().map(|s| s.unwrap() as f32 / i16::MAX as f32).collect();
//! let embeddings = embedder.forward(&samples)?;
//! println!("Shape: {:?}", embeddings.shape());
//! ```

